const pool = require("../../config/db");
const ApiError = require("../../utils/ApiError");

async function createTheatre({ name, city, address }) {
  const { rows } = await pool.query(
    "INSERT INTO theatres (name, city, address) VALUES ($1, $2, $3) RETURNING *",
    [name, city, address]
  );
  return rows[0];
}

async function listTheatres({ city }) {
  if (city) {
    const { rows } = await pool.query(
      "SELECT * FROM theatres WHERE LOWER(city) = LOWER($1) ORDER BY name",
      [city]
    );
    return rows;
  }
  const { rows } = await pool.query("SELECT * FROM theatres ORDER BY city, name");
  return rows;
}

async function getTheatre(id) {
  const theatre = await pool.query("SELECT * FROM theatres WHERE id = $1", [id]);
  if (!theatre.rows[0]) throw new ApiError(404, "Theatre not found");

  const screens = await pool.query(
    "SELECT * FROM screens WHERE theatre_id = $1 ORDER BY name",
    [id]
  );

  return { ...theatre.rows[0], screens: screens.rows };
}

// Screen and all its seats are created in ONE transaction
async function createScreen(theatreId, { name, rows, seatsPerRow, premiumRows }) {
  const premium = premiumRows ?? 0;
  const client = await pool.connect();

  try {
    await client.query("BEGIN");

    const theatre = await client.query("SELECT id FROM theatres WHERE id = $1", [
      theatreId,
    ]);
    if (!theatre.rowCount) throw new ApiError(404, "Theatre not found");

    const screenRes = await client.query(
      `INSERT INTO screens (theatre_id, name, rows_count, seats_per_row)
       VALUES ($1, $2, $3, $4)
       RETURNING *`,
      [theatreId, name, rows, seatsPerRow]
    );
    const screen = screenRes.rows[0];

    // Last rows are premium. Row A, B, C... are generated by chr()
    await client.query(
      `INSERT INTO seats (screen_id, row_label, seat_number, seat_type)
       SELECT $1::uuid, chr(64 + r), n,
              CASE WHEN r > $2::int THEN 'premium' ELSE 'regular' END
       FROM generate_series(1, $3::int) AS r,
            generate_series(1, $4::int) AS n`,
      [screen.id, rows - premium, rows, seatsPerRow]
    );

    await client.query("COMMIT");
    return { ...screen, total_seats: rows * seatsPerRow };
  } catch (err) {
    await client.query("ROLLBACK");
    if (err.code === "23505") {
      throw new ApiError(409, "Screen name already exists in this theatre");
    }
    throw err;
  } finally {
    client.release();
  }
}

module.exports = { createTheatre, listTheatres, getTheatre, createScreen };